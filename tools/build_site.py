"""Build docs/*.html from site-src/*.html: adds the shared head, nav and footer.
Each source file starts with: <!-- Page title | Meta description -->
Usage: python3 tools/build_site.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC, OUT = ROOT / "site-src", ROOT / "docs"
REPO = "https://github.com/ronitgupta43-ops/country-skills"
PAGES = [("india", "India"), ("canada", "Canada"), ("us", "US"), ("creators", "Creators"), ("crypto", "Crypto")]
SLOTS = ("window.hallmarkSlots = (m) => { for (const [k, v] of Object.entries(m)) { const s = document.querySelector(`[data-slot=\"${k}\"]`); if (!s) continue; const im = new Image(); im.src = typeof v === 'string' ? v : v.src; im.alt = (typeof v === 'object' && v.alt) || s.dataset.alt || ''; s.querySelectorAll(':scope > img').forEach((o) => o.remove()); s.prepend(im); } };\n"
         "document.querySelectorAll('[data-slot] img').forEach((i) => { if (i.complete && !i.naturalWidth) i.remove(); else i.addEventListener('error', () => i.remove(), { once: true }); });")


def links(current):
    cur = ' aria-current="page"'
    return "".join(f'<li><a href="{p}.html"{cur if p == current else ""}>{n}</a></li>' for p, n in PAGES)


def page(name, body):
    m = re.match(r"<!--\s*(.+?)\s*\|\s*(.+?)\s*-->\n", body)
    title, desc = m.group(1), m.group(2)
    return f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>{title}</title>
<meta name="description" content="{desc}">
<meta property="og:title" content="{title}">
<meta property="og:description" content="{desc}">
<link rel="stylesheet" href="site.css">
</head>
<body class="fibre">
<!-- generated by tools/build_site.py from site-src/{name}.html; edit the source -->
<header class="container nav">
  <a class="wordmark" href="index.html">Country Skills</a>
  <ul>{links(name)}</ul>
  <a class="btn btn--primary" href="index.html#install">Install free</a>
</header>
<main>
{body[m.end():].strip()}
</main>
<footer class="container footer">
  <p class="mast">Country Skills</p>
  <nav aria-label="Footer"><ul><li><a href="index.html">Home</a></li>{links(name)}<li><a href="{REPO}">GitHub</a></li></ul></nav>
  <p>Home page photograph: <a href="https://commons.wikimedia.org/wiki/File:Vallee-brouillard.jpg">Thomas Bresson</a>, CC BY 3.0.</p>
  <p>Free and open source under the MIT licence. Rules checked for 2026 and reviewed every January.</p>
  <p>These skills explain and calculate. They are not tax, legal or financial advice, so check big decisions with a professional.</p>
</footer>
<script src="calc.js"></script>
<script src="site.js"></script>
<script>{SLOTS}</script>
</body>
</html>
"""


if __name__ == "__main__":
    stale = []
    for src in sorted(SRC.glob("*.html")):
        out, html = OUT / src.name, page(src.stem, src.read_text(encoding="utf-8"))
        if "--check" in sys.argv:
            if not out.exists() or out.read_text(encoding="utf-8") != html:
                stale.append(out.name)
        else:
            out.write_text(html, encoding="utf-8")
    if stale:
        sys.exit("Out of date, run python3 tools/build_site.py: " + ", ".join(stale))
